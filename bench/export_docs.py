"""Export bench/results/*.json for the in-app docs (ui/src/docs/benchmarkData.ts).

    python -m bench.export_docs

Run after `python -m bench.run`, then rebuild the web app; the Benchmarks page renders
straight from this file, so every number on it comes from a recorded run.
"""
from __future__ import annotations

import json
from pathlib import Path

from .report import COLORS, ORDER

HERE = Path(__file__).parent
OUT = HERE.parent / "ui" / "src" / "docs" / "benchmarkData.ts"

HEADER = """// Generated by `python -m bench.export_docs` from bench/results/*.json. Don't edit by hand.

export type BenchPoint = { ef: number | null; recall: number; qps: number; p50Ms: number; p99Ms: number };
export type BenchSystem = {
  key: string;
  name: string;
  transport: string;
  color: string;
  buildSeconds: number;
  memoryBytes: number | null;
  operating: BenchPoint;
  concurrentQps: number | null;
  clientMode: string | null;
  filtered: Record<"50%" | "10%" | "1%" | "0.1%", { recall: number; p50Ms: number }>;
  sweep: BenchPoint[];
};
export type BenchmarkSet = {
  dataset: string;
  n: number;
  dimension: number;
  m: number;
  efConstruction: number;
  clients: number;
  machine: string;
  dockerVm: string | null;
  finishedAt: string;
  versions: Record<string, string>;
  systems: BenchSystem[];
};

"""


def _point(p: dict) -> dict:
    return {"ef": p["ef"], "recall": round(p["recall"], 4), "qps": round(p["qps"], 1),
            "p50Ms": round(p["p50Ms"], 3), "p99Ms": round(p["p99Ms"], 3)}


def main() -> None:
    sets = []
    for path in sorted((HERE / "results").glob("*.json")):
        result = json.loads(path.read_text())
        if not result.get("systems"):
            continue
        systems = sorted(result["systems"].items(), key=lambda kv: ORDER.index(kv[0]) if kv[0] in ORDER else len(ORDER))
        env = result["environment"]
        docker = env.get("docker")
        versions = {k: str(v) for s in result["systems"].values() for k, v in s.get("info", {}).items()
                    if k in ("needledb", "faiss", "qdrant", "pgvector", "postgres", "vectorType")}
        sets.append({
            "dataset": result["dataset"], "n": result["n"], "dimension": result["dimension"],
            "m": result["m"], "efConstruction": result["efConstruction"],
            "clients": next(iter(result["systems"].values()))["threads"],
            "machine": f"{env.get('cpu')} · {env.get('cpuCount')} cores · {env.get('memoryBytes', 0) / 2**30:.0f} GB RAM",
            "dockerVm": f"{docker['cpus']} CPUs · {docker['memoryBytes'] / 2**30:.1f} GB" if docker else None,
            "finishedAt": max(s.get("finishedAt", "") for s in result["systems"].values()),
            "versions": versions,
            "systems": [{
                "key": key, "name": s["name"], "transport": s["transport"], "color": COLORS.get(key, "#444444"),
                "buildSeconds": round(s["buildSeconds"], 1), "memoryBytes": s["memoryBytes"],
                "operating": _point(s["operatingPoint"]),
                "concurrentQps": round(s["concurrentQps"], 1) if s.get("concurrentQps") else None,
                "clientMode": s.get("clientMode"),
                "filtered": {k: {"recall": round(v["recall"], 4), "p50Ms": round(v["p50Ms"], 3)} for k, v in s["filtered"].items()},
                "sweep": [_point(p) for p in s["sweep"]],
            } for key, s in systems],
        })
    sets.sort(key=lambda s: (-s["dimension"], s["n"]))
    OUT.write_text(HEADER + "export const BENCHMARKS: BenchmarkSet[] = " + json.dumps(sets, indent=2) + ";\n")
    print(f"wrote {OUT} ({len(sets)} datasets)")


if __name__ == "__main__":
    main()
